def get_config(body_font: str, heading_font: str, selected_color: str) -> dict[str, Any]:
    """
    Build a Shopify `config/settings_data.json` payload with frontend-provided values.

    Notes:
    - This uses a JSON template with placeholder tokens: body_font, heading_font, selected_color
    - Placeholders are replaced as whole-words to avoid accidental substring matches
    """

    replacements = {
        "body_font": body_font,
        "heading_font": heading_font,
        "selected_color": selected_color,
    }

    rendered = _SETTINGS_DATA_TEMPLATE
    for token, value in replacements.items():
        rendered = re.sub(rf"\b{re.escape(token)}\b", json.dumps(value), rendered)

    for token in replacements:
        if re.search(rf"\b{re.escape(token)}\b", rendered):
            raise ValueError(
                f"settings_data template still contains unresolved token {token!r}"
            )

    return json.loads(rendered)